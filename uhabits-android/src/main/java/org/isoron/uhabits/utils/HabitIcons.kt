package org.isoron.uhabits.utils

import android.content.Context
import android.graphics.Typeface
import androidx.annotation.RawRes
import org.isoron.uhabits.R
import org.isoron.uhabits.core.ui.IconEntry
import org.isoron.uhabits.core.ui.IconSearch

/**
 * The icons a habit can have, from two bundled fonts: Material Icons, stored by bare name (e.g.
 * "fitness_center"), and Font Awesome Free solid, stored as "fa:<name>" (e.g. "fa:tooth").
 * The data files are generated by tools/generate-icon-data.py.
 */
object HabitIcons {
    private const val FA_PREFIX = "fa:"

    /** Icons for common habits, shown first when the search box is empty. */
    private val SUGGESTED = listOf(
        "fitness_center", "fa:dumbbell", "directions_run", "directions_walk", "directions_bike",
        "pool", "hiking", "sports_gymnastics", "self_improvement", "fa:person-praying", "fa:brain",
        "psychology", "fa:tooth", "shower", "water_drop", "restaurant", "local_cafe",
        "menu_book", "school", "edit_note", "bedtime", "alarm", "wb_sunny", "medication",
        "favorite", "savings", "cleaning_services", "work", "music_note", "palette",
        "no_adult_content", "fa:eye-slash", "smoke_free", "vape_free", "fa:ban-smoking",
        "fa:cannabis", "fa:joint", "fa:bong", "no_drinks", "block", "no_cell"
    )

    private class Catalog(
        val entries: List<IconEntry>,
        val glyphs: Map<String, String>
    )

    private var materialFont: Typeface? = null
    private var faFont: Typeface? = null
    private var catalog: Catalog? = null

    fun typeface(context: Context, name: String?): Typeface {
        val assets = context.applicationContext.assets
        return if (name != null && name.startsWith(FA_PREFIX)) {
            faFont ?: Typeface.createFromAsset(assets, "fa-solid-900.ttf").also { faFont = it }
        } else {
            materialFont
                ?: Typeface.createFromAsset(assets, "MaterialIcons-Regular.ttf")
                    .also { materialFont = it }
        }
    }

    /** The character to draw with [typeface] for the icon [name], or null if it is unknown. */
    fun glyph(context: Context, name: String?): String? {
        if (name == null) return null
        return catalog(context).glyphs[name]
    }

    /** "fa:person-praying" -> "person praying", for display. */
    fun displayName(name: String): String =
        name.removePrefix(FA_PREFIX).replace('_', ' ').replace('-', ' ')

    /**
     * Icon names matching [query] by name or keyword, best first. With a blank query, the
     * suggested icons come first, followed by all the others.
     */
    fun search(context: Context, query: String): List<String> =
        IconSearch.search(catalog(context).entries, query).map { it.name }

    @Synchronized
    private fun catalog(context: Context): Catalog {
        catalog?.let { return it }
        val resources = context.applicationContext.resources
        val glyphs = linkedMapOf<String, String>()
        val keywords = mutableMapOf<String, String>()

        fun lines(@RawRes id: Int, block: (String) -> Unit) =
            resources.openRawResource(id).bufferedReader().useLines { it.forEach(block) }

        fun glyphOf(hex: String): String? =
            hex.toIntOrNull(16)?.let { String(Character.toChars(it)) }

        val material = sortedMapOf<String, String>()
        lines(R.raw.material_icon_codepoints) { line ->
            val parts = line.trim().split(' ')
            if (parts.size == 2) glyphOf(parts[1])?.let { material[parts[0]] = it }
        }
        lines(R.raw.material_icon_keywords) { line ->
            val (name, words) = line.split('|', limit = 2).let { it[0] to it.getOrElse(1) { "" } }
            keywords[name] = words
        }
        val fa = sortedMapOf<String, String>()
        lines(R.raw.fa_icon_codepoints) { line ->
            val (head, words) = line.split('|', limit = 2).let { it[0] to it.getOrElse(1) { "" } }
            val parts = head.trim().split(' ')
            if (parts.size == 2) {
                glyphOf(parts[1])?.let {
                    fa[FA_PREFIX + parts[0]] = it
                    keywords[FA_PREFIX + parts[0]] = words
                }
            }
        }
        glyphs.putAll(material)
        glyphs.putAll(fa)

        val ordered = SUGGESTED.filter { it in glyphs } + glyphs.keys.filter { it !in SUGGESTED }
        val result = Catalog(
            entries = ordered.map { IconEntry(it, keywords[it] ?: "") },
            glyphs = glyphs
        )
        catalog = result
        return result
    }
}
